let currentLang = 'el';

function setLanguage(lang) {
  currentLang = lang;
  const t = translations[lang];
  document.querySelectorAll('[data-lang]').forEach(el => {
    const key = el.dataset.lang;
    if (t[key]) el.innerHTML = t[key];
  });
  document.documentElement.lang = lang === 'el' ? 'el' : 'en';
  document.getElementById('langToggle').textContent = lang === 'el' ? 'EN' : 'EL';
}

function initScrollReveal() {
  const els = document.querySelectorAll('.reveal-up, .reveal-left, .reveal-right, .reveal-scale');
  if (els.length === 0) return;
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.15, rootMargin: '0px 0px -50px 0px' });
  els.forEach(el => observer.observe(el));
}

let countersAnimated = false;
function initCounters() {
  const counters = document.querySelectorAll('.counter');
  if (counters.length === 0) return;
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting && !countersAnimated) {
        countersAnimated = true;
        counters.forEach(counter => {
          const target = parseFloat(counter.dataset.target);
          const decimal = parseInt(counter.dataset.decimal) || 0;
          const duration = 1500;
          const step = Math.max(target / 60, 0.01);
          let current = 0;
          const timer = setInterval(() => {
            current += step;
            if (current >= target) {
              current = target;
              clearInterval(timer);
            }
            counter.textContent = decimal > 0 ? current.toFixed(decimal) : Math.floor(current);
          }, duration / 60);
        });
        observer.disconnect();
      }
    });
  }, { threshold: 0.3 });
  counters.forEach(c => observer.observe(c.closest('.stat-item')));
}

function initCarousel() {
  const track = document.getElementById('carouselTrack');
  const prev = document.getElementById('carouselPrev');
  const next = document.getElementById('carouselNext');
  const dots = document.getElementById('carouselDots');
  if (!track) return;
  const slides = track.querySelectorAll('.carousel-slide');
  if (slides.length === 0) return;
  let idx = 0;
  slides.forEach((_, i) => {
    const dot = document.createElement('button');
    dot.className = 'carousel-dot' + (i === 0 ? ' active' : '');
    dot.addEventListener('click', () => goTo(i));
    dots.appendChild(dot);
  });
  function goTo(i) {
    idx = i;
    track.style.transform = `translateX(-${idx * 100}%)`;
    dots.querySelectorAll('.carousel-dot').forEach((d, j) => d.classList.toggle('active', j === idx));
  }
  if (prev) prev.addEventListener('click', () => goTo(idx > 0 ? idx - 1 : slides.length - 1));
  if (next) next.addEventListener('click', () => goTo(idx < slides.length - 1 ? idx + 1 : 0));
  let autoSlide = setInterval(() => { if (slides.length > 0) goTo((idx + 1) % slides.length); }, 5000);
  const container = document.querySelector('.carousel-container');
  if (container) {
    container.addEventListener('mouseenter', () => clearInterval(autoSlide));
    container.addEventListener('mouseleave', () => { autoSlide = setInterval(() => goTo((idx + 1) % slides.length), 5000); });
  }
}

function initContactForm() {
  const form = document.getElementById('contactForm');
  if (!form) return;
  const submitBtn = document.getElementById('formSubmit');
  const successMsg = document.getElementById('formSuccess');
  form.addEventListener('submit', (e) => {
    e.preventDefault();
    const name = document.getElementById('formName').value.trim();
    const email = document.getElementById('formEmail').value.trim();
    const phone = document.getElementById('formPhone').value.trim();
    const message = document.getElementById('formMessage').value.trim();
    if (!name || !email || !message) return;
    submitBtn.classList.add('loading');
    const mailto = `mailto:pariskup72@gmail.com?subject=${encodeURIComponent(currentLang === 'el' ? 'Νέο μήνυμα από τον ιστότοπο Γαλήνη' : 'New message from Galini website')}&body=${encodeURIComponent(
      `${currentLang === 'el' ? 'Όνομα' : 'Name'}: ${name}\n${currentLang === 'el' ? 'Email' : 'Email'}: ${email}\n${currentLang === 'el' ? 'Τηλέφωνο' : 'Phone'}: ${phone}\n\n${message}`
    )}`;
    setTimeout(() => {
      submitBtn.classList.remove('loading');
      form.reset();
      successMsg.classList.add('visible');
      setTimeout(() => successMsg.classList.remove('visible'), 5000);
      window.open(mailto, '_blank');
    }, 800);
  });
}

function initFloatingButtons() {
  const whatsapp = document.getElementById('whatsappBtn');
  const backTop = document.getElementById('backToTop');
  let lastScroll = 0;
  window.addEventListener('scroll', () => {
    const y = window.scrollY;
    if (y > 500) {
      whatsapp.classList.add('visible');
      backTop.classList.add('visible');
    } else {
      whatsapp.classList.remove('visible');
      backTop.classList.remove('visible');
    }
    lastScroll = y;
  }, { passive: true });
  if (backTop) {
    backTop.addEventListener('click', () => window.scrollTo({ top: 0, behavior: 'smooth' }));
  }
}

function initGalleryLightbox() {
  document.querySelectorAll('.gallery-item').forEach(item => {
    item.addEventListener('click', () => {
      const img = item.querySelector('img');
      if (!img) return;
      const overlay = document.createElement('div');
      overlay.className = 'lightbox';
      overlay.innerHTML = `<div class="lightbox-content"><button class="lightbox-close" aria-label="Close">&times;</button><img src="${img.src}" alt="${img.alt}"></div>`;
      document.body.appendChild(overlay);
      document.body.style.overflow = 'hidden';
      overlay.addEventListener('click', (e) => { if (e.target === overlay) close(); });
      overlay.querySelector('.lightbox-close').addEventListener('click', close);
      function close() { overlay.remove(); document.body.style.overflow = ''; }
    });
  });
}

document.addEventListener('DOMContentLoaded', () => {
  setLanguage('el');
  initScrollReveal();
  initCounters();
  initCarousel();
  initContactForm();
  initFloatingButtons();
  initGalleryLightbox();

  document.getElementById('langToggle').addEventListener('click', () => {
    setLanguage(currentLang === 'el' ? 'en' : 'el');
  });

  const navbar = document.getElementById('navbar');
  const navToggle = document.getElementById('navToggle');
  const navLinks = document.getElementById('navLinks');

  window.addEventListener('scroll', () => {
    navbar.classList.toggle('scrolled', window.scrollY > 50);
  }, { passive: true });

  navToggle.addEventListener('click', () => navLinks.classList.toggle('active'));
  navLinks.querySelectorAll('a').forEach(link => {
    link.addEventListener('click', () => navLinks.classList.remove('active'));
  });

  document.querySelectorAll('a[href^="#"]').forEach(anchor => {
    anchor.addEventListener('click', e => {
      const target = document.querySelector(anchor.getAttribute('href'));
      if (target) { e.preventDefault(); target.scrollIntoView({ behavior: 'smooth' }); }
    });
  });
});
